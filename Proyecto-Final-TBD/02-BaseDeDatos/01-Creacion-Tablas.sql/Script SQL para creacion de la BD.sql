-- ============================================================
CREACIÓN DE TABLAS 
-- ============================================================

-- 1. TABLAS MAESTRAS
CREATE TABLE PERSONA (
    CI VARCHAR2(15) PRIMARY KEY,
    NOMBRE VARCHAR2(50) NOT NULL,
    APELLIDO VARCHAR2(50) NOT NULL,
    TELEFONO VARCHAR2(20),
    CORREO VARCHAR2(50),
    ESTADO VARCHAR2(20) DEFAULT 'ACTIVO',
    DIRECCION VARCHAR2(100),
    HUELLA_DIGITAL BLOB
);

CREATE TABLE TIPO_VEHICULO (
    ID_TIPO_VEHICULO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(30) NOT NULL,
    DESCRIPCION VARCHAR2(100)
);

CREATE TABLE TIPO_SERVICIO (
    ID_TIPO_SERVICIO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(30) NOT NULL,
    DESCRIPCION VARCHAR2(100)
);

CREATE TABLE COMBUSTIBLE (
    ID_COMBUSTIBLE NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(30) NOT NULL,
    TIPO VARCHAR2(20) NOT NULL,
    ESTADO VARCHAR2(20) DEFAULT 'ACTIVO'
);

CREATE TABLE EMPRESA_TRANSPORTE (
    ID_EMPRESA NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(50) NOT NULL,
    NIT VARCHAR2(20) UNIQUE,
    TELEFONO VARCHAR2(20),
    DIRECCION VARCHAR2(100),
    ESTADO VARCHAR2(20) DEFAULT 'ACTIVO'
);

CREATE TABLE ESTACION_SERVICIO (
    ID_ESTACION NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(50) NOT NULL,
    DIRECCION VARCHAR2(100),
    CIUDAD VARCHAR2(30),
    DEPARTAMENTO VARCHAR2(30),
    LATITUD NUMBER(10,8),
    LONGITUD NUMBER(11,8),
    ESTADO VARCHAR2(20) DEFAULT 'ACTIVA'
);

CREATE TABLE REGLA (
    ID_REGLA NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(50),
    DESCRIPCION VARCHAR2(200),
    FECHA_INICIO DATE,
    FECHA_FIN DATE,
    ESTADO VARCHAR2(20)
);

-- 2. VEHICULOS, RUAT, CONDUCTORES Y CISTERNAS
CREATE TABLE VEHICULO (
    PLACA_VEHICULO VARCHAR2(10) PRIMARY KEY,
    CI VARCHAR2(15),
    ID_TIPO_VEHICULO NUMBER,
    ESTADO VARCHAR2(20) DEFAULT 'ACTIVO',
    RENDIMIENTO_PROMEDIO NUMBER(5,2),
    CONSTRAINT FK_VEHICULO_PERSONA FOREIGN KEY (CI) REFERENCES PERSONA(CI),
    CONSTRAINT FK_VEHICULO_TIPO FOREIGN KEY (ID_TIPO_VEHICULO) REFERENCES TIPO_VEHICULO(ID_TIPO_VEHICULO)
);

CREATE TABLE RUAT (
    ID_RUAT NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CI_PROPIETARIO VARCHAR2(15),
    PLACA_VEHICULO VARCHAR2(10) NOT NULL,
    MARCA VARCHAR2(30),
    MODELO VARCHAR2(30),
    ANIO NUMBER(4),
    COLOR VARCHAR2(20),
    CAPACIDAD_TANQUE NUMBER(6,2),
    FECHA_REGISTRO DATE,
    ESTADO_REGISTRO VARCHAR2(20),
    ID_TIPO_SERVICIO NUMBER,
    CONSTRAINT UQ_RUAT_PLACA UNIQUE (PLACA_VEHICULO),
    CONSTRAINT FK_RUAT_VEHICULO FOREIGN KEY (PLACA_VEHICULO) REFERENCES VEHICULO(PLACA_VEHICULO),
    CONSTRAINT FK_RUAT_SERVICIO FOREIGN KEY (ID_TIPO_SERVICIO) REFERENCES TIPO_SERVICIO(ID_TIPO_SERVICIO)
);

CREATE TABLE CONDUCTOR (
    ID_CONDUCTOR NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CI VARCHAR2(15) NOT NULL,
    LICENCIA VARCHAR2(20) UNIQUE,
    ESTADO VARCHAR2(20) DEFAULT 'ACTIVO',
    CONSTRAINT FK_CONDUCTOR_PERSONA FOREIGN KEY (CI) REFERENCES PERSONA(CI)
);

CREATE TABLE CISTERNA (
    PLACA_CISTERNA VARCHAR2(10) PRIMARY KEY,
    ID_EMPRESA NUMBER,
    ID_CONDUCTOR NUMBER,
    CAPACIDAD_LITROS NUMBER(10,2),
    ESTADO VARCHAR2(20) DEFAULT 'ACTIVO',
    CONSTRAINT FK_CISTERNA_EMPRESA FOREIGN KEY (ID_EMPRESA) REFERENCES EMPRESA_TRANSPORTE(ID_EMPRESA),
    CONSTRAINT FK_CISTERNA_CONDUCTOR FOREIGN KEY (ID_CONDUCTOR) REFERENCES CONDUCTOR(ID_CONDUCTOR)
);

-- 3. INFRAESTRUCTURA DE ABASTECIMIENTO
CREATE TABLE SURTIDOR (
    ID_SURTIDOR NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_ESTACION NUMBER,
    ESTADO VARCHAR2(20),
    CUPO_MAX_MENSUAL NUMBER(10,2),
    CONSTRAINT FK_SURTIDOR_ESTACION FOREIGN KEY (ID_ESTACION) REFERENCES ESTACION_SERVICIO(ID_ESTACION)
);

CREATE TABLE DISPENSADOR (
    ID_DISPENSADOR NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_SURTIDOR NUMBER,
    ID_COMBUSTIBLE NUMBER NOT NULL,
    NUMERO_MANGUERA NUMBER(10),
    ESTADO VARCHAR2(20),
    CONSTRAINT FK_DISPENSADOR_SURTIDOR FOREIGN KEY (ID_SURTIDOR) REFERENCES SURTIDOR(ID_SURTIDOR),
    CONSTRAINT FK_DISPENSADOR_COMBUSTIBLE FOREIGN KEY (ID_COMBUSTIBLE) REFERENCES COMBUSTIBLE(ID_COMBUSTIBLE)
);

CREATE TABLE PLANTA_ALMACENAMIENTO (
    ID_PLANTA NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(50) NOT NULL,
    UBICACION VARCHAR2(100),
    CAPACIDAD_MAXIMA NUMBER(12,2)
);

-- 4. REGLAS Y PRECIOS
CREATE TABLE REGLA_CUPO (
    ID_REGLA_CUPO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_REGLA NUMBER,
    ID_TIPO_VEHICULO NUMBER,
    PERIODO VARCHAR2(30),
    LITROS_MAXIMOS NUMBER(6,2),
    FRECUENCIA_MAXIMA NUMBER(10),
    FECHA_INICIO DATE,
    FECHA_FIN DATE,
    PERIODO_FRECUENCIA VARCHAR2(20),
    CONSTRAINT FK_REGLA_CUPO_REGLA FOREIGN KEY (ID_REGLA) REFERENCES REGLA(ID_REGLA),
    CONSTRAINT FK_REGLA_CUPO_TIPO FOREIGN KEY (ID_TIPO_VEHICULO) REFERENCES TIPO_VEHICULO(ID_TIPO_VEHICULO)
);

CREATE TABLE REGLA_PRECIO (
    ID_REGLA_PRECIO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_REGLA NUMBER,
    ID_COMBUSTIBLE NUMBER,
    PRECIO_SUBVENCIONADO NUMBER(8,2),
    PRECIO_INTERNACIONAL NUMBER(8,2),
    FECHA_INICIO DATE,
    FECHA_FIN DATE,
    ESTADO VARCHAR2(20),
    CONSTRAINT FK_REGLA_PRECIO_REGLA FOREIGN KEY (ID_REGLA) REFERENCES REGLA(ID_REGLA),
    CONSTRAINT FK_REGLA_PRECIO_COMB FOREIGN KEY (ID_COMBUSTIBLE) REFERENCES COMBUSTIBLE(ID_COMBUSTIBLE)
);

CREATE TABLE PRECIO_DIARIO_REFERENCIA (
    ID_PRECIO_DIARIO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_COMBUSTIBLE NUMBER,
    FECHA DATE,
    TIPO_CAMBIO_DOLAR NUMBER(8,4),
    PRECIO_INTERNACIONAL_USD NUMBER(8,2),
    PRECIO_INTERNACIONAL_BS NUMBER(8,2),
    CONSTRAINT FK_PRECIO_DIARIO_COMB FOREIGN KEY (ID_COMBUSTIBLE) REFERENCES COMBUSTIBLE(ID_COMBUSTIBLE),
    CONSTRAINT UQ_PRECIO_DIARIO_COMB_FECHA UNIQUE (ID_COMBUSTIBLE, FECHA)
);

CREATE TABLE PRECIO_COMBUSTIBLE (
    ID_PRECIO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_COMBUSTIBLE NUMBER,
    PRECIO_COMPRA NUMBER(8,2),
    PRECIO_VENTA NUMBER(8,2),
    FECHA_INICIO DATE,
    FECHA_FIN DATE,
    CONSTRAINT FK_PRECIO_COMBUSTIBLE FOREIGN KEY (ID_COMBUSTIBLE) REFERENCES COMBUSTIBLE(ID_COMBUSTIBLE)
);

-- 5. AUTORIZACIONES, CUPOS Y EXISTENCIAS
CREATE TABLE AUTORIZACION_VEHICULO (
    ID_AUTORIZACION NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PLACA_VEHICULO VARCHAR2(10),
    ID_REGLA NUMBER,
    FECHA_INICIO DATE,
    FECHA_FIN DATE,
    ESTADO VARCHAR2(20),
    MOTIVO VARCHAR2(200),
    CONSTRAINT FK_AUTORIZACION_VEHICULO FOREIGN KEY (PLACA_VEHICULO) REFERENCES VEHICULO(PLACA_VEHICULO),
    CONSTRAINT FK_AUTORIZACION_REGLA FOREIGN KEY (ID_REGLA) REFERENCES REGLA(ID_REGLA)
);

CREATE TABLE CUPO_SERVICIO (
    ID_CUPO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_SURTIDOR NUMBER,
    ID_COMBUSTIBLE NUMBER,
    ID_REGLA_CUPO NUMBER,
    FECHA_ACTUALIZACION DATE,
    FECHA_FIN DATE,
    CANTIDAD_LITROS NUMBER(10,2),
    CONSTRAINT FK_CUPO_SERVICIO_SURTIDOR FOREIGN KEY (ID_SURTIDOR) REFERENCES SURTIDOR(ID_SURTIDOR),
    CONSTRAINT FK_CUPO_SERVICIO_COMB FOREIGN KEY (ID_COMBUSTIBLE) REFERENCES COMBUSTIBLE(ID_COMBUSTIBLE),
    CONSTRAINT FK_CUPO_SERVICIO_REGLA FOREIGN KEY (ID_REGLA_CUPO) REFERENCES REGLA_CUPO(ID_REGLA_CUPO),
    CONSTRAINT CK_CUPO_SERVICIO_FECHAS CHECK (FECHA_FIN IS NULL OR FECHA_FIN >= FECHA_ACTUALIZACION)
);

CREATE TABLE EXISTENCIA_PLANTA (
    ID_EXISTENCIA_PLANTA NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_PLANTA NUMBER,
    ID_COMBUSTIBLE NUMBER,
    CANTIDAD_DISPONIBLE NUMBER(12,2),
    FECHA_ACTUALIZACION TIMESTAMP,
    CONSTRAINT FK_EXISTENCIA_PLANTA FOREIGN KEY (ID_PLANTA) REFERENCES PLANTA_ALMACENAMIENTO(ID_PLANTA),
    CONSTRAINT FK_EXISTENCIA_PLANTA_COMB FOREIGN KEY (ID_COMBUSTIBLE) REFERENCES COMBUSTIBLE(ID_COMBUSTIBLE)
);

CREATE TABLE EXISTENCIA_SURTIDOR (
    ID_EXISTENCIA NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_SURTIDOR NUMBER,
    ID_COMBUSTIBLE NUMBER,
    CANTIDAD_DISPONIBLE NUMBER(10,2),
    FECHA_ACTUALIZACION TIMESTAMP,
    CONSTRAINT FK_EXISTENCIA_SURTIDOR FOREIGN KEY (ID_SURTIDOR) REFERENCES SURTIDOR(ID_SURTIDOR),
    CONSTRAINT FK_EXISTENCIA_SURTIDOR_COMB FOREIGN KEY (ID_COMBUSTIBLE) REFERENCES COMBUSTIBLE(ID_COMBUSTIBLE)
);

-- 6. OPERACIONES: DESPACHOS Y VENTAS
CREATE TABLE DESPACHO (
    ID_DESPACHO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_PLANTA NUMBER,
    PLACA_CISTERNA VARCHAR2(10),
    ID_SURTIDOR NUMBER,
    ID_COMBUSTIBLE NUMBER,
    CANTIDAD_LITROS NUMBER(10,2),
    FECHA_HORA TIMESTAMP,
    ESTADO VARCHAR2(20),
    CONSTRAINT FK_DESPACHO_PLANTA FOREIGN KEY (ID_PLANTA) REFERENCES PLANTA_ALMACENAMIENTO(ID_PLANTA),
    CONSTRAINT FK_DESPACHO_CISTERNA FOREIGN KEY (PLACA_CISTERNA) REFERENCES CISTERNA(PLACA_CISTERNA),
    CONSTRAINT FK_DESPACHO_SURTIDOR FOREIGN KEY (ID_SURTIDOR) REFERENCES SURTIDOR(ID_SURTIDOR),
    CONSTRAINT FK_DESPACHO_COMB FOREIGN KEY (ID_COMBUSTIBLE) REFERENCES COMBUSTIBLE(ID_COMBUSTIBLE)
);

CREATE TABLE VENTA (
    ID_VENTA NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_DISPENSADOR NUMBER NOT NULL,
    CI_COMPRADOR VARCHAR2(15) NOT NULL,
    PLACA_VEHICULO VARCHAR2(10),
    ID_REGLA_CUPO NUMBER,
    ID_REGLA_PRECIO NUMBER,
    FECHA_HORA TIMESTAMP,
    CANTIDAD_LITROS NUMBER(8,2),
    TIPO_PRECIO VARCHAR2(20),
    HUELLA_VERIFICADA NUMBER(1) DEFAULT 0,
    MONTO_TOTAL NUMBER(10,2),
    PRECIO_UNITARIO NUMBER(8,2),
    KILOMETRAJE NUMBER(10),
    ID_PRECIO_DIARIO NUMBER,
    CONSTRAINT FK_VENTA_DISPENSADOR FOREIGN KEY (ID_DISPENSADOR) REFERENCES DISPENSADOR(ID_DISPENSADOR),
    CONSTRAINT FK_VENTA_COMPRADOR FOREIGN KEY (CI_COMPRADOR) REFERENCES PERSONA(CI),
    CONSTRAINT FK_VENTA_VEHICULO FOREIGN KEY (PLACA_VEHICULO) REFERENCES VEHICULO(PLACA_VEHICULO),
    CONSTRAINT FK_VENTA_REGLA_CUPO FOREIGN KEY (ID_REGLA_CUPO) REFERENCES REGLA_CUPO(ID_REGLA_CUPO),
    CONSTRAINT FK_VENTA_REGLA_PRECIO FOREIGN KEY (ID_REGLA_PRECIO) REFERENCES REGLA_PRECIO(ID_REGLA_PRECIO),
    CONSTRAINT FK_VENTA_PRECIO_DIARIO FOREIGN KEY (ID_PRECIO_DIARIO) REFERENCES PRECIO_DIARIO_REFERENCIA(ID_PRECIO_DIARIO),
    CONSTRAINT CK_VENTA_HUELLA CHECK (HUELLA_VERIFICADA IN (0,1))
);

-- 7. CUPOS Y RESUMENES DE CONSUMO
CREATE TABLE CUPO_SEMANAL_PERSONA (
    ID_CUPO_SEMANAL NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CI VARCHAR2(15) NOT NULL,
    ID_REGLA_CUPO NUMBER NOT NULL,
    SEMANA NUMBER(2) NOT NULL,
    ANIO NUMBER(4) NOT NULL,
    CUPO_ASIGNADO NUMBER(8,2) NOT NULL,
    CONSTRAINT FK_CUPO_SEMANAL_PERSONA FOREIGN KEY (CI) REFERENCES PERSONA(CI),
    CONSTRAINT FK_CUPO_SEMANAL_REGLA_CUPO FOREIGN KEY (ID_REGLA_CUPO) REFERENCES REGLA_CUPO(ID_REGLA_CUPO),
    CONSTRAINT UQ_CUPO_SEMANAL_PERSONA UNIQUE (CI, SEMANA, ANIO),
    CONSTRAINT CK_CUPO_SEMANAL_SEMANA CHECK (SEMANA BETWEEN 1 AND 53)
);

CREATE TABLE CONSUMO_SEMANAL (
    ID_CONSUMO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CUPO_SEMANAL NUMBER NOT NULL,
    LITROS_SUBSIDIADOS NUMBER(8,2),
    LITROS_INTERNACIONAL NUMBER(8,2),
    NUM_CARGAS NUMBER(10),
    FECHA_ULTIMA_CARGA DATE,
    CONSTRAINT UQ_CONSUMO_SEMANAL_CUPO UNIQUE (ID_CUPO_SEMANAL),
    CONSTRAINT FK_CONSUMO_SEMANAL_CUPO FOREIGN KEY (ID_CUPO_SEMANAL) REFERENCES CUPO_SEMANAL_PERSONA(ID_CUPO_SEMANAL)
);

CREATE TABLE CONSUMO_MENSUAL (
    ID_CONSUMO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CI VARCHAR2(15) NOT NULL,
    MES NUMBER(2) NOT NULL,
    ANIO NUMBER(4) NOT NULL,
    LITROS_SUBVENCIONADOS NUMBER(10,2),
    LITROS_INTERNACIONAL NUMBER(10,2),
    NUMERO_CARGAS NUMBER(10),
    FECHA_ULTIMA_CARGA DATE,
    CONSTRAINT FK_CONSUMO_MENSUAL_PERSONA FOREIGN KEY (CI) REFERENCES PERSONA(CI),
    CONSTRAINT UQ_CONSUMO_MENSUAL_PERSONA UNIQUE (CI, MES, ANIO),
    CONSTRAINT CK_CONSUMO_MENSUAL_MES CHECK (MES BETWEEN 1 AND 12)
);

-- 8. ALERTAS Y AUDITORIA
CREATE TABLE ALERTA (
    ID_ALERTA NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PLACA_VEHICULO VARCHAR2(10),
    ID_VENTA NUMBER,
    CI VARCHAR2(15), 
    TIPO_ALERTA VARCHAR2(50),
    DESCRIPCION VARCHAR2(200),
    FECHA_HORA TIMESTAMP,
    ESTADO VARCHAR2(20),
    CONSTRAINT FK_ALERTA_VEHICULO FOREIGN KEY (PLACA_VEHICULO) REFERENCES VEHICULO(PLACA_VEHICULO),
    CONSTRAINT FK_ALERTA_VENTA FOREIGN KEY (ID_VENTA) REFERENCES VENTA(ID_VENTA),
    CONSTRAINT FK_ALERTA_PERSONA FOREIGN KEY (CI) REFERENCES PERSONA(CI)
);

CREATE TABLE AUDITORIA_GENERAL (
    ID_AUDITORIA NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CI VARCHAR2(15),
    ACCION VARCHAR2(20),
    MODULO VARCHAR2(30), 
    ID_REGISTRO_AFECTADO NUMBER(10),
    FECHA_HORA TIMESTAMP,
    IP_ORIGEN VARCHAR2(45),
    CONSTRAINT FK_AUDITORIA_PERSONA FOREIGN KEY (CI) REFERENCES PERSONA(CI)
);

CREATE TABLE AUDITORIA_VENTA (
    ID_AUDITORIA_VENTA NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_AUDITORIA NUMBER NOT NULL UNIQUE,
    ID_VENTA NUMBER,
    DATOS_ANTERIORES CLOB,
    DATOS_NUEVOS CLOB,
    CONSTRAINT FK_AUDITORIA_VENTA_GENERAL FOREIGN KEY (ID_AUDITORIA) REFERENCES AUDITORIA_GENERAL(ID_AUDITORIA),
    CONSTRAINT FK_AUDITORIA_VENTA_VENTA FOREIGN KEY (ID_VENTA) REFERENCES VENTA(ID_VENTA)
);

CREATE TABLE AUDITORIA_REGLA (
    ID_AUDITORIA_REGLA NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_AUDITORIA NUMBER NOT NULL UNIQUE,
    ID_REGLA NUMBER,
    DATOS_NUEVOS CLOB,
    DATOS_ANTERIORES CLOB,
    CONSTRAINT FK_AUDITORIA_REGLA_GENERAL FOREIGN KEY (ID_AUDITORIA) REFERENCES AUDITORIA_GENERAL(ID_AUDITORIA),
    CONSTRAINT FK_AUDITORIA_REGLA_REGLA FOREIGN KEY (ID_REGLA) REFERENCES REGLA(ID_REGLA)
);

CREATE TABLE AUDITORIA_DESPACHO (
    ID_AUDITORIA_DESPACHO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_AUDITORIA NUMBER NOT NULL UNIQUE,
    ID_DESPACHO NUMBER,
    DATOS_NUEVOS CLOB,
    DATOS_ANTERIORES CLOB,
    CONSTRAINT FK_AUDITORIA_DESPACHO_GENERAL FOREIGN KEY (ID_AUDITORIA) REFERENCES AUDITORIA_GENERAL(ID_AUDITORIA),
    CONSTRAINT FK_AUDITORIA_DESPACHO_DESPACHO FOREIGN KEY (ID_DESPACHO) REFERENCES DESPACHO(ID_DESPACHO)
);

